"""Build the static place data used by the web app and the backend.

Sources (both open data, bundled so the app needs no extra downloads):
- Country shapes: world-atlas 2.0.2 (Natural Earth 1:50m), simplified with topojson-simplify.
- Countries, capitals and cities: GeoNames via the `geonamescache` package (CC BY 4.0).

Usage (only needed when you want to rebuild the data):
    pip install geonamescache
    npm i world-atlas@2.0.2 topojson-simplify@3.0.3 topojson-client@3.1.0
    node scripts/simplify.js node_modules/world-atlas/countries-50m.json countries.json names.json
    python scripts/build_places.py countries.json names.json
"""
import json
import os
import sys

import geonamescache

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OBSOLETE = {"CS", "AN"}
NAME_TO_ISO = {"Kosovo": "XK", "Somaliland": "SO", "N. Cyprus": "CY", "Siachen Glacier": None,
               "Indian Ocean Ter.": None}


def main(topo_path, names_path):
    gc = geonamescache.GeonamesCache()
    countries = gc.get_countries()
    cities = list(gc.get_cities().values())
    by_cc = {}
    for c in cities:
        by_cc.setdefault(c["countrycode"], []).append(c)

    out = []
    for cc, co in sorted(countries.items()):
        if cc in OBSOLETE or cc not in by_cc:
            continue
        cs = sorted(by_cc[cc], key=lambda c: -c["population"])
        cap_name = (co.get("capital") or "").strip()
        cap = next((c for c in cs if c["name"] == cap_name or cap_name in c.get("alternatenames", [])), None) or cs[0]
        big = [c for c in cs if c["population"] >= 150_000][:30]
        for c in cs:
            if len(big) >= 3:
                break
            if c not in big:
                big.append(c)
        if cap not in big:
            big.insert(0, cap)
        out.append({
            "c": cc, "n": co["name"], "i3": co["iso3"], "num": int(co["isonumeric"] or 0),
            "cont": co["continentcode"], "pop": co["population"], "a": int(float(co.get("areakm2") or 0)),
            "cap": [cap["name"], round(cap["latitude"], 4), round(cap["longitude"], 4)],
            "cities": [[c["name"], round(c["latitude"], 4), round(c["longitude"], 4), c["population"]] for c in big],
        })

    num_to_cc = {p["num"]: p["c"] for p in out}
    topo = json.load(open(topo_path))
    names = json.load(open(names_path))
    for g, (fid, fname) in zip(topo["objects"]["countries"]["geometries"], names):
        cc = num_to_cc.get(int(fid)) if fid else NAME_TO_ISO.get(fname)
        g["properties"] = {"name": fname, "cc": cc}

    os.makedirs(os.path.join(ROOT, "air2green", "data"), exist_ok=True)
    with open(os.path.join(ROOT, "air2green", "data", "places.json"), "w") as f:
        json.dump(out, f, separators=(",", ":"), ensure_ascii=False)
    with open(os.path.join(ROOT, "web", "geo.js"), "w") as f:
        f.write("/* Country shapes: Natural Earth via world-atlas 2.0.2. Places: GeoNames (CC BY 4.0). Generated by scripts/build_places.py */\n")
        f.write("window.A2G_TOPO=" + json.dumps(topo, separators=(",", ":")) + ";\n")
        f.write("window.A2G_PLACES=" + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
    mapped = sum(1 for g in topo["objects"]["countries"]["geometries"] if g["properties"]["cc"])
    print(f"countries with data: {len(out)}, cities: {sum(len(p['cities']) for p in out)}, map shapes linked: {mapped}/{len(names)}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
